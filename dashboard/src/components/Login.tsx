"use client";
import { useState } from "react";
import { z } from "zod";
import { request } from "@/lib/api";
export function Login({ onSuccess }: { onSuccess: () => void }) {
  const [secret, setSecret] = useState(""),
    [error, setError] = useState(""),
    [busy, setBusy] = useState(false);
  return (
    <div className="login">
      <form
        className="panel login-card"
        onSubmit={async (event) => {
          event.preventDefault();
          setBusy(true);
          setError("");
          try {
            const result = await request(
              "/auth/token",
              z.object({
                access_token: z.string(),
                expires_at: z.string(),
                token_type: z.string(),
              }),
              { method: "POST", body: JSON.stringify({ secret }) },
            );
            sessionStorage.setItem("tracelore.token", result.access_token);
            setSecret("");
            onSuccess();
          } catch (error) {
            setError(
              error instanceof Error ? error.message : "Unable to sign in",
            );
          } finally {
            setBusy(false);
          }
        }}
      >
        <div className="brand">
          <span className="orbit">◉</span> tracelore
          <span className="badge">CONTROL PLANE</span>
        </div>
        <h1>See where it started.</h1>
        <p>Trace the incident. Inspect the evidence. Test the fix.</p>
        <label>
          Dashboard secret
          <input
            type="password"
            autoComplete="current-password"
            required
            value={secret}
            onChange={(event) => setSecret(event.target.value)}
          />
        </label>
        {error && (
          <p role="alert" className="error">
            {error}
          </p>
        )}
        <button disabled={busy}>
          {busy ? "Connecting…" : "Open observatory →"}
        </button>
        <p className="subtle">
          Use the secret generated by setup. Your session stays in this browser
          tab.
        </p>
      </form>
    </div>
  );
}
